const fs = require('fs');
const path = require('path');
const {
  withAndroidManifest,
  withDangerousMod,
  withInfoPlist,
} = require('@expo/config-plugins');

/**
 * Pins the production API's TLS certificate chain to Let's Encrypt's root keys,
 * during `expo prebuild`, with the operating systems' own declarative pinning:
 * Android's network security config `<pin-set>` and iOS's `NSPinnedDomains`.
 * No library — both platforms enforce it below every HTTP stack the app uses
 * (OkHttp / NSURLSession, so axios, fetch and the assistant's native callers).
 *
 * **Why.** Every request and response body is AES-GCM wrapped, but the key is
 * built into the app, so anyone who extracts it can read traffic they can see.
 * TLS is what keeps them from seeing it — unless the device trusts a proxy's
 * certificate. Pinning closes that: a chain that does not lead to one of these
 * roots is refused even when the device trusts it.
 *
 * **What is pinned.** The SHA-256 of the SubjectPublicKeyInfo of all four ISRG
 * roots — X1 (RSA), X2 (ECDSA) and the 2025 generation YE (ECDSA) and YR (RSA).
 * Every chain Let's Encrypt can issue ends at one of them, so a renewal, a key
 * type change or Let's Encrypt moving to its new roots keeps working. Moving the
 * API to ANOTHER certificate authority breaks the app until a build with the new
 * pin ships — `npm run verify:pins` checks the live chain against this list.
 *
 * **What is not.** Only `api.recipely.net`. `dev-api` sits behind Cloudflare,
 * which rotates between certificate authorities on its own; images and the web
 * app are on other hosts.
 *
 * **Expiry.** Android stops enforcing the pins after `PIN_EXPIRATION`, so an
 * old install fails open rather than offline if the pins ever go stale; iOS has
 * no such switch. Move the date forward with each release.
 *
 * Debug builds keep cleartext (Metro is plain http) through a debug-variant copy
 * of the config: once `networkSecurityConfig` is set, Android ignores the debug
 * manifest's `usesCleartextTraffic`.
 *
 * @see https://developer.android.com/privacy-and-security/security-config#CertificatePinning
 * @see https://developer.apple.com/news/?id=g9ejcf8y (Identity Pinning)
 */
const PINNED_HOST = 'api.recipely.net';

const ROOT_PINS = [
  { name: 'ISRG Root X1', spkiSha256: 'C5+lpZ7tcVwmwQIMcRtPbsQtWLABXhQzejna0wHFr8M=' },
  { name: 'ISRG Root X2', spkiSha256: 'diGVwiVYbubAI3RW4hB9xU8e/CH2GnkuvVFZE8zmgzI=' },
  { name: 'ISRG Root YE', spkiSha256: 'sCkq5UWXjg+7mKu9lMhhYF5bGLsy7VI/UNW3tccdR7w=' },
  { name: 'ISRG Root YR', spkiSha256: 'fk6IOKit1ild5647BH06ujSIq5XbCgqlbYl6ANhhi88=' },
];

const PIN_EXPIRATION = '2028-06-30';

const CONFIG_NAME = 'network_security_config';

/** The network security config XML; `cleartext` is true only for the debug variant. */
const networkSecurityConfig = ({ cleartext }) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withApiCertificatePinning.js on every prebuild. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="${cleartext}" />
  <domain-config cleartextTrafficPermitted="false">
    <domain includeSubdomains="false">${PINNED_HOST}</domain>
    <pin-set expiration="${PIN_EXPIRATION}">
${ROOT_PINS.map((pin) => `      <!-- ${pin.name} -->\n      <pin digest="SHA-256">${pin.spkiSha256}</pin>`).join('\n')}
    </pin-set>
  </domain-config>
</network-security-config>
`;

/** Adds the pinned domain to the ATS dictionary, keeping whatever else it holds. */
const withPinnedDomain = (ats = {}) => ({
  ...ats,
  NSPinnedDomains: {
    ...(ats.NSPinnedDomains ?? {}),
    [PINNED_HOST]: {
      NSIncludesSubdomains: false,
      NSPinnedCAIdentities: ROOT_PINS.map((pin) => ({ 'SPKI-SHA256-BASE64': pin.spkiSha256 })),
    },
  },
});

const writeConfig = (projectRoot, variant, cleartext) => {
  const dir = path.join(projectRoot, 'android', 'app', 'src', variant, 'res', 'xml');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${CONFIG_NAME}.xml`), networkSecurityConfig({ cleartext }));
};

const withAndroidPinning = (config) => {
  config = withDangerousMod(config, [
    'android',
    (mod) => {
      writeConfig(mod.modRequest.projectRoot, 'main', false);
      writeConfig(mod.modRequest.projectRoot, 'debug', true);
      return mod;
    },
  ]);
  return withAndroidManifest(config, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (application === undefined) throw new Error('[withApiCertificatePinning] AndroidManifest has no <application>');
    application.$['android:networkSecurityConfig'] = `@xml/${CONFIG_NAME}`;
    return mod;
  });
};

const withIosPinning = (config) =>
  withInfoPlist(config, (mod) => {
    mod.modResults.NSAppTransportSecurity = withPinnedDomain(mod.modResults.NSAppTransportSecurity);
    return mod;
  });

const withApiCertificatePinning = (config) => withIosPinning(withAndroidPinning(config));

module.exports = withApiCertificatePinning;
module.exports.PINNED_HOST = PINNED_HOST;
module.exports.ROOT_PINS = ROOT_PINS;
module.exports.PIN_EXPIRATION = PIN_EXPIRATION;
module.exports.networkSecurityConfig = networkSecurityConfig;
module.exports.withPinnedDomain = withPinnedDomain;
