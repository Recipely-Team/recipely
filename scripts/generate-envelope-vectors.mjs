#!/usr/bin/env node
/**
 * Regenerates the AES-256-GCM parity vectors the three envelope implementations
 * are checked against.
 *
 * Why this exists, and why it is run by hand rather than by the test:
 * - **The oracle must not be the code under test.** The vectors are produced by
 *   `node:crypto` (OpenSSL), while the app's JS envelope uses `@noble/ciphers`
 *   and the native halves use CryptoKit and `javax.crypto`. Four independent
 *   implementations agreeing on one byte string is evidence; an implementation
 *   agreeing with itself is not.
 * - **Committed, not generated at test time.** A fixture regenerated on every
 *   run can never fail — it would simply describe whatever the generator did
 *   today. These bytes are frozen so a change in any of the four is a red test.
 *
 * Run: `node scripts/generate-envelope-vectors.mjs`
 */
import { createCipheriv, randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const IV_BYTES = 12;
const KEY_BYTES = 32;

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'modules',
  'recipely-assistant-kit',
  '__fixtures__',
  'aes-gcm-vectors.json',
);

/**
 * Each case names what it proves, because a vector whose purpose nobody wrote
 * down is a vector nobody dares to change.
 */
const CASES = [
  {
    name: 'ascii-request-body',
    proves: 'the ordinary case: a JSON request body the assistant endpoint would accept',
    plaintext: JSON.stringify({ message: 'what can I cook with two eggs', languageCode: 'en' }),
  },
  {
    name: 'turkish-multibyte',
    proves:
      'UTF-8 is the encoding, not the platform default. An implementation that reaches for UTF-16 or a locale encoding produces a different ciphertext here and the same one for the ASCII case above.',
    plaintext: JSON.stringify({ message: 'İki yumurtayla ne pişirebilirim? Şöyle düşün: çöğen, ğ.', languageCode: 'tr' }),
  },
  {
    name: 'response-envelope',
    proves: 'the direction the native side DECRYPTS: a backend success envelope, `{ data: ... }`',
    plaintext: JSON.stringify({ data: { reply: 'Menemen yapabilirsin.', action: null } }),
  },
  {
    name: 'empty-object',
    proves: 'a 2-byte plaintext still produces a 18-byte sealed payload — the tag is appended, never folded in',
    plaintext: '{}',
  },
  {
    name: 'long-body',
    proves: 'more than one AES block, so a single-block shortcut in any implementation shows up',
    plaintext: JSON.stringify({ message: 'köfte '.repeat(200) }),
  },
];

function seal(keyHex, plaintext) {
  const iv = randomBytes(IV_BYTES);
  const cipher = createCipheriv('aes-256-gcm', Buffer.from(keyHex, 'hex'), iv);
  const body = Buffer.concat([cipher.update(Buffer.from(plaintext, 'utf8')), cipher.final()]);
  // The wire format is ciphertext || 16-byte tag, which is what both CryptoKit's
  // `combined` and `@noble/ciphers` produce, and what the backend expects.
  return {
    ivBase64: iv.toString('base64'),
    payloadBase64: Buffer.concat([body, cipher.getAuthTag()]).toString('base64'),
  };
}

const keyHex = randomBytes(KEY_BYTES).toString('hex');

const vectors = CASES.map(({ name, proves, plaintext }) => ({
  name,
  proves,
  plaintext,
  ...seal(keyHex, plaintext),
}));

// One sealed payload with a flipped last byte — the tag byte. Every
// implementation must REJECT this, and a decrypt that "succeeds" with garbage
// is the failure this case exists to catch.
const tampered = Buffer.from(vectors[0].payloadBase64, 'base64');
tampered[tampered.length - 1] ^= 0x01;

const fixture = {
  $comment:
    'Generated by scripts/generate-envelope-vectors.mjs with node:crypto (OpenSSL), deliberately NOT with the library any of the three implementations use. Read by Jest, JUnit and the Swift parity harness. Do not hand-edit.',
  keyHex,
  ivBytes: IV_BYTES,
  authTagBytes: 16,
  vectors,
  rejects: [
    {
      name: 'tampered-auth-tag',
      proves: 'the GCM tag is verified, not carried. Decrypting this must fail rather than return bytes.',
      ivBase64: vectors[0].ivBase64,
      payloadBase64: tampered.toString('base64'),
    },
    {
      name: 'iv-too-short',
      proves: 'an 11-byte IV is rejected before it reaches the cipher, where some implementations would silently pad it',
      ivBase64: Buffer.alloc(IV_BYTES - 1).toString('base64'),
      payloadBase64: vectors[0].payloadBase64,
    },
    {
      name: 'payload-shorter-than-tag',
      proves: 'a sealed payload that cannot even hold a tag is rejected as malformed',
      ivBase64: vectors[0].ivBase64,
      payloadBase64: Buffer.alloc(8).toString('base64'),
    },
  ],
};

writeFileSync(OUT, `${JSON.stringify(fixture, null, 2)}\n`, 'utf8');
console.log(`wrote ${OUT}`);
console.log(`${vectors.length} vectors, ${fixture.rejects.length} rejection cases`);
