#!/usr/bin/env node
/**
 * Regenerates CHANGELOG.md — the developer-facing history of every release.
 *
 * WHY: the store notes (`fastlane/metadata/…`, `distribution/whatsnew/…`) are
 * overwritten on every release and trimmed for users, so they keep no history.
 * The history already exists in git: every push to `main` gets a `vX.Y.Z` tag
 * (`tag-release` in ci.yml) and every commit on `dev` is a squashed,
 * conventional-commit PR. This script reads both and writes them down.
 *
 * - **Generated, never hand-edited.** `npm run changelog` rewrites the whole
 *   file from the tags, so it cannot drift from what actually shipped.
 * - **Unreleased work is headed with the NEXT version.** Commits after the last
 *   tag are listed under the version the `tag-release` job will stamp when
 *   they reach `main` (`next-version.mjs`: major / minor / patch by the same
 *   rule as ci.yml), marked "unreleased".
 *   The release PR runs this, so its diff shows what the release contains.
 * - **App repo only.** Backend changes ship from `recipely-backend` and are not
 *   in this history.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { nextVersion } from './next-version.mjs';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'CHANGELOG.md');
const REPO_URL = 'https://github.com/Recipely-Team/recipely';
const TAG_PATTERN = /^v(\d+)\.(\d+)\.(\d+)$/;
const SUBJECT_PATTERN = /^(\w+)(?:\(([^)]*)\))?!?:\s*(.+)$/;
const PR_SUFFIX = /\s*\(#(\d+)\)$/;

/** Section order and headings; any other conventional type lands in "Other". */
const GROUPS = [
  { title: 'Features', types: ['feat'] },
  { title: 'Fixes', types: ['fix'] },
  { title: 'Performance', types: ['perf'] },
  { title: 'Refactoring', types: ['refactor'] },
];
const OTHER = 'Other';

const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();

const versionTags = () =>
  git('tag', '--list', 'v*')
    .split('\n')
    .map((tag) => ({ tag, parts: TAG_PATTERN.exec(tag) }))
    .filter(({ parts }) => parts !== null)
    .map(({ tag, parts }) => ({ tag, version: parts.slice(1, 4).map(Number) }))
    .sort((a, b) => a.version[0] - b.version[0] || a.version[1] - b.version[1] || a.version[2] - b.version[2]);

/** Non-merge commit subjects in `range`, oldest first. */
const subjects = (range) => {
  const out = git('log', '--no-merges', '--reverse', '--format=%s', range);
  return out === '' ? [] : out.split('\n');
};

const toEntry = (subject) => {
  const pr = PR_SUFFIX.exec(subject);
  const text = pr === null ? subject : subject.slice(0, pr.index);
  const parsed = SUBJECT_PATTERN.exec(text);
  const type = parsed === null ? OTHER : parsed[1].toLowerCase();
  const scope = parsed?.[2] ? `**${parsed[2]}:** ` : '';
  const summary = parsed === null ? text : parsed[3];
  const link = pr === null ? '' : ` ([#${pr[1]}](${REPO_URL}/pull/${pr[1]}))`;
  return { type, line: `- ${scope}${summary}${link}` };
};

const renderRelease = (heading, lines) => {
  const entries = lines.map(toEntry);
  const known = GROUPS.flatMap((g) => g.types);
  const sections = [
    ...GROUPS.map((g) => ({ title: g.title, items: entries.filter((e) => g.types.includes(e.type)) })),
    { title: OTHER, items: entries.filter((e) => !known.includes(e.type)) },
  ].filter((s) => s.items.length > 0);
  const body = sections.length === 0
    ? ['_No app changes; this release re-shipped the previous build._']
    : sections.flatMap((s) => [`### ${s.title}`, '', ...s.items.map((e) => e.line), '']);
  return [`## ${heading}`, '', ...body].join('\n').trimEnd();
};

const main = () => {
  const tags = versionTags();
  const releases = tags.map(({ tag }, i) => {
    const range = i === 0 ? tag : `${tags[i - 1].tag}..${tag}`;
    const date = git('log', '-1', '--format=%ad', '--date=short', tag);
    return renderRelease(`[${tag.slice(1)}](${REPO_URL}/releases/tag/${tag}) — ${date}`, subjects(range));
  });

  const last = tags.at(-1);
  const pending = last === undefined ? [] : subjects(`${last.tag}..HEAD`);
  if (pending.length > 0) {
    const next = nextVersion(last.version, git('log', '--no-merges', '--format=%s%n%b', `${last.tag}..HEAD`));
    releases.push(renderRelease(`${next.join('.')} — unreleased`, pending));
  }

  const header = [
    '# Changelog',
    '',
    'Every app release, newest first. Generated by `npm run changelog` from the `v*` tags',
    '(`scripts/generate-changelog.mjs`); do not edit by hand. User-facing store notes live in',
    '`fastlane/metadata/` and `distribution/whatsnew/`. Backend changes ship from `recipely-backend`.',
  ].join('\n');
  fs.writeFileSync(OUT, `${[header, ...releases.reverse()].join('\n\n')}\n`);
  if (!process.argv.includes('--quiet')) {
    console.log(`CHANGELOG.md: ${String(tags.length)} release(s)${pending.length > 0 ? ' + unreleased' : ''}`);
  }
};

main();
