#!/usr/bin/env node
/**
 * Writes the localized `AppShortcuts.strings` files from the i18n catalogue,
 * and beside them the `RecipelyIntents.strings` table the intents speak from.
 *
 * WHY a generator and not a hand-kept file: Apple looks the phrases up by their
 * ENGLISH text. The key in the string catalogue has to equal the literal in
 * `RecipelyShortcuts.swift` character for character — with `\(.applicationName)`
 * written as `${applicationName}` — or the lookup misses, Siri matches the
 * English phrase, and all fourteen translations are silently ignored. Nothing
 * fails, nothing logs; the feature simply only works in English.
 *
 * So the two halves are joined on that string rather than on a third naming
 * scheme: every phrase in the Swift is looked up by value in `en.osIntentPhrases`,
 * and a phrase with no match — or a catalogue entry no phrase uses — stops the
 * build. A rename on either side is loud.
 *
 * WHY the legacy `.strings` format and not a String Catalogue: `.xcstrings` is
 * rejected outright below an iOS 17 deployment target — *"AppShortcuts.xcstrings
 * is only supported for iOS 17.0 and above"* — and this app deploys to 15.1. The
 * App Shortcuts themselves are gated at 17.2 and simply do not appear on older
 * systems, but the deployment target is a property of the whole target, so the
 * catalogue format has to follow the oldest OS the app supports rather than the
 * oldest OS the feature does.
 *
 * WHY a second table: the phrases are what the user SAYS, and Apple reads them
 * from `AppShortcuts.strings`; what Siri says BACK — the follow-up question, the
 * line while the app comes forward — is an ordinary `LocalizedStringResource`
 * the intent resolves at run time. It gets its own table rather than the app's
 * `Localizable` so it cannot collide with anything else in the target, and the
 * same rule joins it: every `table: "RecipelyIntents"` literal in the Swift must
 * match an `en.osIntentDialogs` value, every entry must be used, and a dialog
 * written as a bare literal stops the build.
 *
 * Run by `npm run shortcuts`; freshness is enforced by `check:structure`.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const LOCALES_DIR = path.join(ROOT, 'src/presentation/i18n/locales');
const SWIFT = path.join(
  ROOT,
  'modules/recipely-assistant-kit/ios/AppIntents/Shortcuts/RecipelyShortcuts.swift',
);
const OUT_DIR = path.join(ROOT, 'modules/recipely-assistant-kit/ios/Resources');
const STRINGS_FILE = 'AppShortcuts.strings';
const INTENTS_DIR = path.join(ROOT, 'modules/recipely-assistant-kit/ios/AppIntents');
const DIALOG_TABLE = 'RecipelyIntents';
const DIALOG_FILE = `${DIALOG_TABLE}.strings`;

const APP_TOKEN = '{app}';
const APPLE_TOKEN = '${applicationName}';
const SOURCE_LANGUAGE = 'en';

/** `"Ask \(.applicationName)"` → `Ask ${applicationName}`, Apple's own form. */
const toAppleForm = (phrase) => phrase.split(APP_TOKEN).join(APPLE_TOKEN);

/**
 * Reads one locale's flat string block (`osIntentPhrases`, `osIntentDialogs`)
 * without importing TypeScript.
 *
 * A regex rather than a parser because the block is generated by us and its
 * shape is fixed: a flat map of single-quoted or double-quoted strings. A
 * catalogue that ever stops being flat will fail loudly here rather than
 * silently emit fewer phrases.
 */
const readBlock = (code, name) => {
  const src = fs.readFileSync(path.join(LOCALES_DIR, `${code}.ts`), 'utf8');
  const block = new RegExp(`${name}:\\s*\\{([\\s\\S]*?)\\n {2}\\},`).exec(src);
  if (block === null) throw new Error(`${code}.ts has no ${name} block`);
  const entries = {};
  for (const m of block[1].matchAll(/^ {4}(\w+):\s*(['"])([\s\S]*?)\2,$/gm)) {
    entries[m[1]] = m[3];
  }
  return entries;
};

const readPhrases = (code) => readBlock(code, 'osIntentPhrases');

/** Every `.swift` under the intents folder, however deep. */
const swiftSourcesUnder = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return swiftSourcesUnder(full);
    return entry.name.endsWith('.swift') ? [full] : [];
  });

const localeCodes = fs
  .readdirSync(LOCALES_DIR)
  .filter((name) => name.endsWith('.ts'))
  .map((name) => name.replace(/\.ts$/, ''))
  .sort();

const swiftPhrases = [
  ...fs.readFileSync(SWIFT, 'utf8').matchAll(/phrases:\s*\["([^"]*)\\\(\.applicationName\)([^"]*)"\]/g),
].map((m) => `${m[1]}${APP_TOKEN}${m[2]}`);

if (swiftPhrases.length === 0) {
  throw new Error('No App Shortcut phrases found — every phrase must interpolate .applicationName');
}

// Read once per language rather than once per language per phrase: the loop
// below is phrases x locales, and re-parsing each file ten times is 140 reads
// of the same fourteen files.
const phrasesByLocale = new Map(localeCodes.map((code) => [code, readPhrases(code)]));
const english = phrasesByLocale.get(SOURCE_LANGUAGE) ?? readPhrases(SOURCE_LANGUAGE);
const idByEnglish = new Map(Object.entries(english).map(([id, text]) => [text, id]));

const byLocale = new Map(localeCodes.map((code) => [code, []]));
const usedIds = new Set();

for (const phrase of swiftPhrases) {
  const id = idByEnglish.get(phrase);
  if (id === undefined) {
    throw new Error(
      `RecipelyShortcuts.swift says "${phrase}" and no en.osIntentPhrases entry matches it — ` +
        'the English value IS the lookup key, so a phrase with no entry ships untranslated',
    );
  }
  usedIds.add(id);

  for (const code of localeCodes) {
    const text = phrasesByLocale.get(code)?.[id];
    if (text === undefined || text.length === 0) {
      throw new Error(`${code}.ts is missing osIntentPhrases.${id}`);
    }
    if (!text.includes(APP_TOKEN)) {
      throw new Error(
        `${code}.ts osIntentPhrases.${id} does not contain ${APP_TOKEN} — ` +
          'Apple drops a phrase that omits the application name, with no error',
      );
    }
    byLocale.get(code).push([toAppleForm(phrase), toAppleForm(text)]);
  }
}

const unused = Object.keys(english).filter((id) => !usedIds.has(id));
if (unused.length > 0) {
  throw new Error(
    `osIntentPhrases has entries no App Shortcut uses: ${unused.join(', ')} — ` +
      'a phrase nobody says is translated fourteen times for nothing',
  );
}

/** `.strings` is a C-ish format: only the quote and the backslash need escaping. */
const escape = (value) => value.split('\\').join('\\\\').split('"').join('\\"');

const render = (rows) =>
  `${rows.map(([key, value]) => `"${escape(key)}" = "${escape(value)}";`).join('\n')}\n`;

const dialogKeys = [
  ...new Set(
    swiftSourcesUnder(INTENTS_DIR).flatMap((file) => [
      ...fs
        .readFileSync(file, 'utf8')
        .matchAll(new RegExp(`LocalizedStringResource\\(\\s*"([^"]+)",\\s*table:\\s*"${DIALOG_TABLE}"`, 'g')),
    ].map((m) => m[1])),
  ),
];
// A dialog written as a bare literal never reaches the table, so it is spoken
// in English on every phone — which is what "Ask Recipely", "Create Recipe" and
// "Import Recipe" all did. Refused here rather than trusted to review.
const BARE_DIALOG = /(requestValueDialog:\s*"|IntentDialog\(\s*"|IntentDialog\(stringLiteral:\s*"|dialog:\s*")/;
for (const file of swiftSourcesUnder(INTENTS_DIR)) {
  const hit = BARE_DIALOG.exec(fs.readFileSync(file, 'utf8'));
  if (hit !== null) {
    throw new Error(
      `${path.relative(ROOT, file)} writes a Siri dialog as a bare literal (${hit[1]}…) — ` +
        `use LocalizedStringResource("…", table: "${DIALOG_TABLE}") and add it to osIntentDialogs`,
    );
  }
}

const dialogsByLocale = new Map(localeCodes.map((code) => [code, readBlock(code, 'osIntentDialogs')]));
const englishDialogs = dialogsByLocale.get(SOURCE_LANGUAGE);
const dialogIdByEnglish = new Map(Object.entries(englishDialogs).map(([id, text]) => [text, id]));
const usedDialogIds = new Set();
const dialogRowsByLocale = new Map(localeCodes.map((code) => [code, []]));

for (const key of dialogKeys) {
  const id = dialogIdByEnglish.get(key);
  if (id === undefined) {
    throw new Error(
      `An intent reads "${key}" from ${DIALOG_TABLE} and no en.osIntentDialogs entry matches it — ` +
        'the English value IS the lookup key, so Siri would say it in English everywhere',
    );
  }
  usedDialogIds.add(id);
  for (const code of localeCodes) {
    const text = dialogsByLocale.get(code)?.[id];
    if (text === undefined || text.length === 0) {
      throw new Error(`${code}.ts is missing osIntentDialogs.${id}`);
    }
    dialogRowsByLocale.get(code).push([key, text]);
  }
}

const unusedDialogs = Object.keys(englishDialogs).filter((id) => !usedDialogIds.has(id));
if (unusedDialogs.length > 0) {
  throw new Error(
    `osIntentDialogs has entries no intent reads: ${unusedDialogs.join(', ')} — ` +
      'a line Siri never says is translated fourteen times for nothing',
  );
}

let wasStale = false;
const writeTable = (code, name, rows) => {
  const dir = path.join(OUT_DIR, `${code}.lproj`);
  const file = path.join(dir, name);
  const rendered = render(rows);
  const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (previous !== rendered) {
    wasStale = true;
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(file, rendered);
  }
};
for (const [code, rows] of byLocale) writeTable(code, STRINGS_FILE, rows);
for (const [code, rows] of dialogRowsByLocale) writeTable(code, DIALOG_FILE, rows);

// A locale that was deleted from the catalogue must lose its folder too, or the
// plugin keeps copying a language the app no longer ships.
if (fs.existsSync(OUT_DIR)) {
  for (const entry of fs.readdirSync(OUT_DIR)) {
    if (!entry.endsWith('.lproj')) continue;
    if (byLocale.has(entry.replace(/\.lproj$/, ''))) continue;
    wasStale = true;
    fs.rmSync(path.join(OUT_DIR, entry), { recursive: true, force: true });
  }
}

export const isFresh = () => !wasStale;

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(
    `${STRINGS_FILE} — ${swiftPhrases.length} phrases, ${DIALOG_FILE} — ${dialogKeys.length} lines, x ${localeCodes.length} languages`,
  );
}
